import assert from "node:assert/strict";
import { ManualOverrideController, type OverrideEvent } from "../server/lib/manual-override";

const saved = new Map<number, unknown>();
const c = new ManualOverrideController(async (id, state) => { saved.set(id, structuredClone(state)); });
const read = (name: string, value: unknown, time = 1000, id = 1) =>
  c.observe(id, name, value, c.revision(id), time);
assert.equal(c.status(1).durationMinutes, 30);
await read("Boost Switch", true);
assert.equal(c.status(1, 1000).active, false, "coil 13 only enables boost input; it is not active boost");
await read("Fan Speed", "1");
assert.equal(c.status(1, 1000).active, false, "first poll is only a baseline");
c.ownFan(1, 2);
await read("Fan Speed", 2);
assert.equal(c.status(1, 1000).active, false, "own command isn't manual");
await read("Fan Speed", 3, 2000);
assert.equal(c.status(1, 2000).source, "console");
assert.equal(c.status(1, 2000).manualUntil, 2000 + 30 * 60_000);
await read("Fan Speed", 3, 60_000);
assert.equal(c.status(1, 60_000).manualUntil, 2000 + 30 * 60_000, "polls must not renew the deadline");
assert.equal(c.status(1, 2000 + 30 * 60_000).active, false, "deadline expires precisely");
await read("Fan Speed", 3, 2_000_000);
assert.equal(c.status(1, 2_000_000).active, false, "unchanged manual stage doesn't renew after expiry");
await c.manual(1, 2, "app", 3_000_000);
assert.equal(c.status(1, 3_000_000).source, "app");
await c.configure(1, 10);
assert.equal(c.status(1, 3_000_000).manualUntil, 4_800_000, "duration change only affects next intervention");
await c.manual(1, 2, "mqtt", 3_100_000);
assert.equal(c.status(1, 3_100_000).manualUntil, 3_700_000, "same-stage explicit command renews timeout");
assert.equal(c.status(1, 3_100_000).source, "mqtt");
const restored = new ManualOverrideController();
restored.restore(1, saved.get(1));
assert.equal(restored.status(1, 3_200_000).manualUntil, 3_700_000, "restart preserves original deadline");
assert.equal(restored.status(1, 3_700_000).active, false, "restart doesn't extend expiry");
await c.resume(1);
assert.equal(c.status(1).active, false);
const oldRevision = c.revision(1);
await c.manual(1, 1, "app");
await c.observe(1, "Fan Speed", 3, oldRevision);
assert.equal(c.status(1).manualStage, 1, "in-flight stale read cannot overwrite a user command");
await c.resume(1);
await read("Boost Active", true);
await read("Fan Speed", 3);
assert.equal(c.status(1).boost, true);
assert.equal(c.status(1).manualUntil, null, "boost stage isn't manual");
await c.resume(1);
assert.equal(c.status(1).boost, true, "resume must never cancel a hardware boost");
await read("Boost Active", false);
await read("Fan Speed", 1);
assert.equal(c.status(1).active, false, "boost return transition doesn't create 30min override");
await c.startBoost(1);
assert.equal(c.status(1).boostSource, "app");
await read("Fan Speed", 3);
assert.equal(c.status(1).boost, true, "app boost protects before the next device poll");
await c.stopBoost(1);
await read("Fan Speed", 1);
assert.equal(c.status(1).active, false);
c.restore(3, { appBoostUntil: 4000 });
assert.equal(c.status(3, 3000).boost, true, "app boost deadline survives restart");
assert.equal(c.status(3, 4000).boost, false, "app boost expires without renewal");
await c.ruleBoost(1, true);
assert.equal(c.status(1).active, true, "binary sensor timer protects even between device polls");
await c.ruleBoost(1, false);
await read("Fan Speed", 1);
assert.equal(c.status(1).active, false);
assert.equal(c.status(2).active, false, "device isolation");
await assert.rejects(c.configure(1, 0));
await assert.rejects(c.configure(1, 241));
await assert.rejects(c.manual(1, 4, "app"));
await c.manual(1, 2, "app");
await c.resume(1);
await read("Fan Speed", 1, Date.now());
assert.equal(c.status(1).source, "console", "a new console change after resume still works");
console.log("Manueller Vorrang: eigene Befehle, Konsole, App/MQTT, Ablauf, Neustart, Boost/Timer, Rückkehr und veraltete Polls bestanden.");

const events: (OverrideEvent & { deviceId: number })[] = [];
const persisted = new Map<number, unknown>();
const history = new ManualOverrideController(
  async (id, state) => { persisted.set(id, structuredClone(state)); },
  async (id, event) => { events.push({ deviceId: id, ...event }); },
);
const last = () => events.at(-1)!;
await history.observe(10, "Fan Speed", 1, 0, 1000);
await history.observe(10, "Boost Switch", true, 0, 1000);
assert.equal(events.length, 0, "baseline and boost enable aren't intervention events");
await history.manual(10, 2, "mqtt", 2000);
assert.equal(last().actionTaken, "Manueller Vorrang begonnen");
assert.match(last().message, /Home Assistant \/ MQTT.*Stufe 2/);
const started = events.length;
for (let i = 0; i < 10; i++) {
  history.status(10, 3000);
  await history.expire(10, 3000);
  await history.observe(10, "Fan Speed", 2, history.revision(10), 3000);
}
assert.equal(events.length, started, "status and unchanged polls never add history");
await history.manual(10, 3, "app", 4000);
assert.equal(last().actionTaken, "Manueller Vorrang verlängert");
assert.match(last().message, /App.*Stufe 3/);
await history.startBoost(10, 5000);
await history.startBoost(10, 6000);
assert.equal(last().actionTaken, "App-Boost verlängert");
await history.stopBoost(10, 7000);
assert.match(last().message, /Manueller Vorrang für Stufe 3 bleibt/);
await history.automationReturned(10, "Test", "Stufe 1", 8000);
assert.equal(last().actionTaken, "App-Boost beendet", "remaining manual priority prevents premature automation return");
await history.resume(10, 9000);
assert.equal(last().actionTaken, "Manueller Vorrang beendet");
await history.automationReturned(10, "Test", "Stufe 1", 10000);
assert.equal(last().actionTaken, "Automatik wieder aktiv");
assert.match(last().message, /Grundprofil „Test“/);
const returned = events.length;
await history.automationReturned(10, "Test", "Stufe 1", 11000);
await history.resume(10, 11000);
await history.stopBoost(10, 11000);
assert.equal(events.length, returned, "return and repeated stop/resume are idempotent");
await history.manual(10, 1, "console", 12000);
const expiredAt = 12000 + 30 * 60_000;
await history.expire(10, expiredAt + 1000);
assert.equal(last().actionTaken, "Manueller Vorrang abgelaufen");
assert.equal(last().timestamp.getTime(), expiredAt, "expiry timestamp is deadline, not late polling time");
assert.match(last().message, /Gerätekonsole/);
await history.startBoost(10, expiredAt + 2000);
const restoreEvents: OverrideEvent[] = [];
const restarted = new ManualOverrideController(async () => {}, async (_id, event) => { restoreEvents.push(event); });
restarted.restore(10, persisted.get(10));
await restarted.expire(10, expiredAt + 2000 + 30 * 60_000);
await restarted.expire(10, expiredAt + 3000 + 30 * 60_000);
assert.deepEqual(restoreEvents.map(e => e.actionTaken), ["App-Boost abgelaufen"], "restored timer expires once, without invented start");
await restarted.automationReturned(10, "Neustart", "Stufe 1", expiredAt + 4000 + 30 * 60_000);
assert.equal(restoreEvents.at(-1)?.controlType, "automation_return");
await history.ruleBoost(20, true, "Regel „Bad“", 1000);
const ruleStarted = events.length;
await history.ruleBoost(20, true, "Regel „Bad“", 2000);
assert.equal(events.length, ruleStarted, "refreshing a live rule window doesn't generate per-poll extensions");
await history.ruleBoost(20, true, "Regel „Küche“", 2500);
assert.equal(last().actionTaken, "Regel-Boost aktualisiert", "a change of active source remains traceable without stopping boost");
await history.ruleBoost(20, false, undefined, 3000);
assert.match(last().message, /Regel „Küche“/);
await history.observe(20, "Boost Active", true, history.revision(20), 4000);
assert.equal(last().actionTaken, "Geräte-Boost erkannt");
const hardwareStarted = events.length;
await history.observe(20, "Boost Active", true, history.revision(20), 5000);
assert.equal(events.length, hardwareStarted);
await history.observe(20, "Boost Active", false, history.revision(20), 6000);
assert.equal(last().actionTaken, "Geräte-Boost beendet");
assert.equal(last().deviceId, 20);
assert.equal(events.some(e => /CO₂|Hysterese|Wetter/.test(e.message)), false, "priority events never copy old regulation reasons");
console.log("Verlaufsereignisse: Quellen, Verlängerung, Ende/Ablauf, überlagerte Priorität, Neustart, einmalige Rückkehr und keine Poll-Duplikate bestanden.");
