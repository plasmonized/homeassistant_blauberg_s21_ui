import assert from "node:assert/strict";
import { ManualOverrideController } from "../server/lib/manual-override";

const saved = new Map<number, unknown>();
const c = new ManualOverrideController(async (id, state) => { saved.set(id, structuredClone(state)); });
const read = (name: string, value: unknown, time = 1000, id = 1) =>
  c.observe(id, name, value, c.revision(id), time);
assert.equal(c.status(1).durationMinutes, 30);
await read("Boost Switch", true);
assert.equal(c.status(1, 1000).active, false, "coil 13 only enables boost input; it is not active boost");
await read("Fan Speed", "1");
assert.equal(c.status(1, 1000).active, false, "first poll is only a baseline");
c.ownFan(1, 2);
await read("Fan Speed", 2);
assert.equal(c.status(1, 1000).active, false, "own command isn't manual");
await read("Fan Speed", 3, 2000);
assert.equal(c.status(1, 2000).source, "console");
assert.equal(c.status(1, 2000).manualUntil, 2000 + 30 * 60_000);
await read("Fan Speed", 3, 60_000);
assert.equal(c.status(1, 60_000).manualUntil, 2000 + 30 * 60_000, "polls must not renew the deadline");
assert.equal(c.status(1, 2000 + 30 * 60_000).active, false, "deadline expires precisely");
await read("Fan Speed", 3, 2_000_000);
assert.equal(c.status(1, 2_000_000).active, false, "unchanged manual stage doesn't renew after expiry");
await c.manual(1, 2, "app", 3_000_000);
assert.equal(c.status(1, 3_000_000).source, "app");
await c.configure(1, 10);
assert.equal(c.status(1, 3_000_000).manualUntil, 4_800_000, "duration change only affects next intervention");
await c.manual(1, 2, "mqtt", 3_100_000);
assert.equal(c.status(1, 3_100_000).manualUntil, 3_700_000, "same-stage explicit command renews timeout");
assert.equal(c.status(1, 3_100_000).source, "mqtt");
const restored = new ManualOverrideController();
restored.restore(1, saved.get(1));
assert.equal(restored.status(1, 3_200_000).manualUntil, 3_700_000, "restart preserves original deadline");
assert.equal(restored.status(1, 3_700_000).active, false, "restart doesn't extend expiry");
await c.resume(1);
assert.equal(c.status(1).active, false);
const oldRevision = c.revision(1);
await c.manual(1, 1, "app");
await c.observe(1, "Fan Speed", 3, oldRevision);
assert.equal(c.status(1).manualStage, 1, "in-flight stale read cannot overwrite a user command");
await c.resume(1);
await read("Boost Active", true);
await read("Fan Speed", 3);
assert.equal(c.status(1).boost, true);
assert.equal(c.status(1).manualUntil, null, "boost stage isn't manual");
await c.resume(1);
assert.equal(c.status(1).boost, true, "resume must never cancel a hardware boost");
await read("Boost Active", false);
await read("Fan Speed", 1);
assert.equal(c.status(1).active, false, "boost return transition doesn't create 30min override");
await c.startBoost(1);
assert.equal(c.status(1).boostSource, "app");
await read("Fan Speed", 3);
assert.equal(c.status(1).boost, true, "app boost protects before the next device poll");
await c.stopBoost(1);
await read("Fan Speed", 1);
assert.equal(c.status(1).active, false);
c.restore(3, { appBoostUntil: 4000 });
assert.equal(c.status(3, 3000).boost, true, "app boost deadline survives restart");
assert.equal(c.status(3, 4000).boost, false, "app boost expires without renewal");
c.ruleBoost(1, true);
assert.equal(c.status(1).active, true, "binary sensor timer protects even between device polls");
c.ruleBoost(1, false);
await read("Fan Speed", 1);
assert.equal(c.status(1).active, false);
assert.equal(c.status(2).active, false, "device isolation");
await assert.rejects(c.configure(1, 0));
await assert.rejects(c.configure(1, 241));
await assert.rejects(c.manual(1, 4, "app"));
await c.manual(1, 2, "app");
await c.resume(1);
await read("Fan Speed", 1, Date.now());
assert.equal(c.status(1).source, "console", "a new console change after resume still works");
console.log("Manueller Vorrang: eigene Befehle, Konsole, App/MQTT, Ablauf, Neustart, Boost/Timer, Rückkehr und veraltete Polls bestanden.");
